/** 在 textarea 光标处插入文本，返回新内容与新光标位置 */
export function insertAtCursor(
  value: string,
  insert: string,
  start: number,
  end: number,
): { value: string; caret: number } {
  const next = value.slice(0, start) + insert + value.slice(end)
  return { value: next, caret: start + insert.length }
}
